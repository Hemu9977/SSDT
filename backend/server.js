// Hop count from the app back out to the client, so req.ip resolves to the real
// viewer rather than a proxy.
//
// Verified 2026-08-12: api.fortexa.aevus.jp is a CNAME straight to
// fortexa-alb-…elb.amazonaws.com, and responses carry no CloudFront headers — so
// the API path is ALB -> ECS, exactly ONE trusted hop. (The frontend is behind
// CloudFront; the API is not. infrastructure/api-cloudfront-response-headers.json
// describes a distribution that is not in the live DNS path.)
//
// This value must match the real topology. Too LOW and req.ip is a proxy address,
// so every user shares one rate-limit bucket. Too HIGH and Express trusts one more
// X-Forwarded-For entry than exists — which the client controls, letting anyone
// forge their own rate-limit key. Raise it to 2 only if a CDN is put in front.
const TRUSTED_PROXY_HOPS = Number.parseInt(process.env.TRUSTED_PROXY_HOPS, 10);
app.set('trust proxy', Number.isFinite(TRUSTED_PROXY_HOPS) ? TRUSTED_PROXY_HOPS : 1);

// Comma-separated list in FRONTEND_URL supports multiple production domains,
// e.g. "https://fortexa.aevus.jp"
const defaultFrontendOrigins = ['https://fortexa.aevus.jp'];
const rawFrontendOrigins = process.env.FRONTEND_URL;
if (!rawFrontendOrigins && process.env.NODE_ENV === 'production') {
  console.warn('[CORS] FRONTEND_URL is not set in production; using safe defaults.');
}
const allowedOriginsSet = new Set(
  (rawFrontendOrigins || defaultFrontendOrigins.join(','))
    .split(',').map(o => o.trim()).filter(Boolean)
);
if (process.env.NODE_ENV !== 'production') {
  ['http://localhost:3000', 'http://localhost:3002', 'http://localhost:3003']
    .forEach(o => allowedOriginsSet.add(o));
}

const corsOptions = {
  origin(origin, callback) {
    // Allow server-to-server calls (no Origin header) and known origins
    if (!origin || allowedOriginsSet.has(origin)) return callback(null, true);
    console.warn(`[CORS] Blocked request from: ${origin}`);
    callback(new Error('Not allowed by CORS'));
  },
  credentials: true,
  methods: ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'],
  allowedHeaders: ['Content-Type', 'x-auth-token', 'Authorization'],
  maxAge: 86400, // cache preflight 24h
};

// Ensure CORS headers are present even when errors are generated by middleware that
// short-circuits the normal response flow (e.g. thrown errors, auth failures).
// NOTE: This cannot affect responses generated upstream by ALB/CloudFront (e.g. 502/504).
function applyCorsToResponse(req, res) {
  const origin = req.headers?.origin;
  if (!origin) return;
  if (!allowedOriginsSet.has(origin)) return;
  res.setHeader('Access-Control-Allow-Origin', origin);
  res.setHeader('Vary', 'Origin');
  res.setHeader('Access-Control-Allow-Credentials', 'true');
}

app.use(cors(corsOptions));
// Explicit preflight handler — must come before rate limiters and routes so
// OPTIONS requests never reach authLimiter or route handlers (which assume a body).
app.options(/.*/, cors(corsOptions));

// ─── STRIPE WEBHOOK — must come BEFORE express.json() ────────────────────────
// Stripe requires the raw body (Buffer) to verify the webhook signature.
// Mounting it here with express.raw() ensures json() middleware is NOT applied.
