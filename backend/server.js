// ── /health — lightweight liveness probe (ECS health check target) ───────────
// Returns 200 immediately; ECS uses this to decide whether to route traffic.
// Intentionally minimal — no DB or Redis calls so it never blocks.
app.get('/health', (req, res) => {
  const mem = process.memoryUsage();
  res.status(200).json({
    status:    'healthy',
    timestamp: new Date().toISOString(),
    uptime:    Math.floor(process.uptime()),
    memory: {
      heapUsedMB:  Math.round(mem.heapUsed  / 1048576),
      heapTotalMB: Math.round(mem.heapTotal / 1048576),
      rssMB:       Math.round(mem.rss       / 1048576),
    },
  });
});

// ── /ready — readiness probe (checks dependencies before accepting scan traffic) ─
// ECS Service Connect / ALB can use this to temporarily remove unhealthy tasks.
app.get('/ready', async (req, res) => {
  const checks = {};
  let allReady = true;

  // MongoDB
  const mongoose = require('mongoose');
  const mongoState = mongoose.connection.readyState;
  // 1 = connected, 2 = connecting
  checks.mongodb = { ready: mongoState === 1, state: ['disconnected','connected','connecting','disconnecting'][mongoState] ?? mongoState };
  if (mongoState !== 1) allReady = false;

  // Redis (best-effort — non-blocking ping)
  if (process.env.REDIS_URL) {
    try {
      const { getPublisher } = require('./config/redis');
      const pub = getPublisher();
      if (pub.status === 'ready') {
        let clientStats = {};
        try {
          const info = await pub.info('clients');
          const lines = info.split('\n');
          let connected = 0;
          let max = 0;
          for (const line of lines) {
            if (line.startsWith('connected_clients:')) connected = parseInt(line.split(':')[1].trim(), 10);
            if (line.startsWith('maxclients:')) max = parseInt(line.split(':')[1].trim(), 10);
          }
          clientStats = {
            connected_clients: connected,
            maxclients: max,
            warning: (max > 0 && connected > 0.8 * max) ? 'High connection usage' : undefined
          };
        } catch (_) {}
        checks.redis = { ready: true, status: 'ready', ...clientStats };
      } else {
        checks.redis = { ready: false, status: pub.status };
        allReady = false;
      }
    } catch {
      checks.redis = { ready: false, status: 'unavailable' };
      allReady = false;
    }
  } else {
    checks.redis = { ready: false, status: 'not_configured' };
    allReady = false;
  }

  // WebCheck container (optional — degraded not down)
  try {
    const { checkHealth } = require('./services/webCheckService');
    const webCheckOk = await checkHealth();
    checks.webcheck = { ready: webCheckOk };
    if (!webCheckOk) allReady = false;
  } catch {
    checks.webcheck = { ready: false, status: 'unavailable' };
    allReady = false;
  }

  // Active scan metrics
  try {
    const { getActiveScanCount, getMetrics } = require('./services/webCheckService');
    checks.webCheckScans = {
      active:    getActiveScanCount(),
      ...getMetrics(),
    };
  } catch { /* non-critical */ }

  res.status(allReady ? 200 : 503).json({
    ready:     allReady,
    timestamp: new Date().toISOString(),
    checks,
  });
});

