// Graceful shutdown — ECS sends SIGTERM on deploy/scale-in, waits 30s then SIGKILL
const shutdown = (signal) => {
  console.log(`\n${signal} received. Closing server gracefully...`);
  server.close(async () => {
    // Drain in-process worker first so BullMQ releases job locks cleanly.
    if (inProcessWorker) {
      try {
        await inProcessWorker.close();
        inProcessWorker = null;
      } catch (e) {
        console.error('⚠️  Failed to close BullMQ scan worker:', e.message);
      }
    }
    if (inProcessZapWorker) {
      try {
        await inProcessZapWorker.close();
        inProcessZapWorker = null;
      } catch (e) {
        console.error('⚠️  Failed to close BullMQ ZAP worker:', e.message);
      }
    }
    // Drain BullMQ queue connections (scan + zap) before closing Redis singletons
    try {
      const { closeScanQueue } = require('./queues/scanQueue');
      const { closeZapQueue }  = require('./queues/zapQueue');
      await Promise.all([closeScanQueue(), closeZapQueue()]);
    } catch (_) {}
    // Close Redis singleton connections cleanly
    try {
      const { disconnectAll } = require('./config/redis');
      await disconnectAll();
    } catch (_) {}
    // Release keep-alive socket pool so ECS task terminates cleanly
    try {
      const { destroyHttpClient } = require('./utils/httpClient');
      destroyHttpClient();
    } catch (_) {}
    console.log('✅ HTTP server closed. Exiting.');
    process.exit(0);
  });
  // Force-exit if server hasn't closed within 25s (before ECS sends SIGKILL at 30s)
  setTimeout(() => {
    console.error('⚠️  Graceful shutdown timed out. Forcing exit.');
    process.exit(1);
  }, 25000);
};
process.on('SIGTERM', () => shutdown('SIGTERM'));
process.on('SIGINT', () => shutdown('SIGINT'));

process.on('unhandledRejection', (reason) => {
  console.error('❌ Unhandled Promise Rejection:', reason);
});
process.on('uncaughtException', (err) => {
  console.error('💥 Uncaught Exception:', err);
  shutdown('uncaughtException');
});

async function startServer() {
  try {
    await connectDB();

    try {
      gridfsService.initialize('zap_reports');
      gridfsService.initialize('zap_auth_reports');
      gridfsService.initialize('webcheck_results');
      console.log('✅ GridFS initialized (buckets: zap_reports, zap_auth_reports, webcheck_results)');
    } catch (error) {
      console.error('⚠️  GridFS initialization failed:', error.message);
      console.error('   Large file storage may not work properly');
    }

    try {
      startCleanupJob();
      console.log('✅ Cleanup job scheduler started');
    } catch (error) {
      console.error('⚠️  Cleanup job initialization failed:', error.message);
    }

    // ── Redis + real-time scan progress ──────────────────────────────────
    if (process.env.REDIS_URL) {
      try {
        // Run Redis client count/health check on startup
        await checkRedisClientHealth();

        // Publisher: used by scanProgressService to broadcast progress events
        const publisher = getPublisher();
        setPublisher(publisher);

        // Direct in-process emitter — avoids Redis round-trip when worker runs
        // in the same process as the server (the default single-container mode)
        setDirectEmitter((scanId, userId, data) => emitScanProgress(scanId, userId, data));

        // Subscriber: receives events published by standalone worker processes
        // and forwards them to Socket.IO rooms
        const subscriber = getSubscriber();
        initializeScanProgressSubscriber(subscriber);

        console.log('✅ Redis pub/sub connected (scan progress channel active)');

        // Start in-process BullMQ worker unless an external worker is running
        // (set DISABLE_WORKER=true when deploying a dedicated worker ECS task)
        if (process.env.DISABLE_WORKER !== 'true') {
          inProcessWorker    = createScanWorker(publisher);
          inProcessZapWorker = createZapWorker(publisher);
          console.log('✅ In-process BullMQ scan + ZAP workers started');

          // Confirm the task role can actually reach ECS. Without this check a missing
          // IAM policy stays invisible until the first scan of the day fails on recycle.
          // Deliberately not awaited — this must never block or fail startup.
          const { preflightEcsAccess } = require('./services/zapRecycler');
          preflightEcsAccess().catch(err =>
            console.error('[ZapRecycle] preflight threw unexpectedly:', err.message)
          );
        } else {
          console.log('ℹ️  DISABLE_WORKER=true — expecting external worker process');
        }
      } catch (redisErr) {
        console.error('⚠️  Redis connection failed:', redisErr.message);
        console.error('   Real-time scan progress will be unavailable.');
        console.error('   Set REDIS_URL to enable WebSocket scan updates.');
      }
    } else {
      console.warn('⚠️  REDIS_URL not set — WebSocket scan progress and BullMQ disabled.');
      console.warn('   Scans will NOT run. Please set REDIS_URL in your environment.');
    }

    server.listen(PORT, '0.0.0.0', () => {
      console.log('\n=================================');
      console.log('🚀 Server started successfully!');
      console.log(`📡 Listening on port ${PORT}`);
      console.log('🔌 Socket.IO notifications enabled');
      if (process.env.REDIS_URL) {
        console.log('⚡ Real-time scan progress via WebSocket enabled');
      }
      console.log('=================================\n');
    });

  } catch (err) {
    console.error(' Fatal: could not connect to MongoDB on startup:', err.message);
    process.exit(1);
  }
}

startServer();
